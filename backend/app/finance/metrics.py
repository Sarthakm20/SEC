"""Metric registry: reported line items (XBRL concepts) and derived metrics (deterministic formulas).

Reported items list candidate us-gaap concepts in priority order because filers tag the same
economic line item differently (Apple/Microsoft: RevenueFromContractWithCustomer…, NVIDIA: Revenues;
NVIDIA capex: PaymentsToAcquireProductiveAssets). The engine picks, per company, the candidate with
the best multi-year coverage so that YoY comparisons use one consistent definition.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Literal


@dataclass(frozen=True)
class ReportedItem:
    key: str
    label: str
    concepts: tuple[str, ...]
    period_type: Literal["duration", "instant"]
    unit: str = "USD"
    synonyms: tuple[str, ...] = ()


@dataclass(frozen=True)
class DerivedMetric:
    key: str
    label: str
    formula: str  # over item keys; growth metrics use *_prev for prior year
    result_unit: Literal["ratio", "USD"]
    display_percent: bool
    definition: str
    synonyms: tuple[str, ...] = ()
    optional_items: tuple[str, ...] = ()  # treated as 0 when not reported (with a warning)
    cross_checks: tuple[str, ...] = field(default_factory=tuple)


