def all_metric_keys() -> list[str]:
    return list(REPORTED) + list(DERIVED)


def label_for(key: str) -> str:
    if key in REPORTED:
        return REPORTED[key].label
    if key in DERIVED:
        return DERIVED[key].label
    return key
